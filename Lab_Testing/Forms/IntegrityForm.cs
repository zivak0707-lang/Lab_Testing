namespace Lab_Testing;

// Правила контрольної (режим доброчесності): що записується під час тесту.
// Контрольна починається лише після підтвердження «Я проходжу тест самостійно і чесно»
public partial class IntegrityForm : Form
{
    public IntegrityForm(BankSettings settings)
    {
        InitializeComponent();
        RichTextFormatter.Show(rtbRules, RulesText(settings));
        UpdateStartButton();
    }

    // Коли учень підтвердив правила (записується у файл результату)
    public DateTime AcceptedAt { get; private set; }

    // Текст правил під налаштування вчителя. Кількість дозволених виходів показуємо відкрито:
    // правило, про яке учень не знав, було б нечесним, а попередження після виходу однаково його називають.
    // Головне — кожен вихід бачить вчитель, навіть якщо до ліміту ще далеко
    public static string RulesText(BankSettings settings)
    {
        IntegritySettings s = settings.Integrity;

        string limit = s.ExitLimit > 0
            ? $"- Після **{s.ExitLimit}-го виходу** контрольну буде завершено достроково — з тими відповідями, які ви встигли дати."
            : "- Кількість виходів не обмежено, але **кожен вихід побачить вчитель**.";

        string capture = s.HideFromCapture
            ? "- Вікно тесту не видно на знімках і записах екрана. Спроби зробити знімок записуються."
            : "- Спроби зробити знімок екрана (Print Screen, «Ножиці») записуються.";

        return string.Join("\n",
            "## Що відбуватиметься",
            $"- Контрольна відкриється **на весь екран** поверх інших вікон. Час — {settings.ControlTimeMinutes} хв.",
            "- Виходити з вікна тесту (Alt+Tab, клік в інше вікно, згортання) не можна. **Кожен вихід записується**: " +
            "коли, на скільки секунд і на якому питанні.",
            limit,
            $"- Дуже короткі втрати фокусу (до {s.ShortExitSeconds} с — наприклад, системне сповіщення) не рахуються, " +
            "але теж записуються.",
            capture,
            "- Також записуються: кількість моніторів, підключення через віддалений робочий стіл, час на кожне питання.",
            "- Ще одну копію програми під час контрольної відкрити не можна.",
            "## Якщо потрібно вийти",
            "- Кнопка **«✕»** угорі праворуч або Alt+F4 — завершити контрольну (програма перепитає).",
            "- Кнопка **«—»** угорі праворуч згортає тест, але це теж вихід з вікна, і його буде записано.",
            "## Хто це побачить",
            "Усе записане зберігається у файлі результату. Файл захищено підписом — змінити записи неможливо. " +
            "Вчитель побачить їх у таблиці результатів.");
    }

    private void ChkHonest_CheckedChanged(object? sender, EventArgs e)
    {
        UpdateStartButton();
    }

    // «Почати контрольну» — лише після підтвердження (неактивна кнопка — сіра)
    private void UpdateStartButton()
    {
        btnStart.Enabled = chkHonest.Checked;
        btnStart.BackColor = chkHonest.Checked ? Theme.Success : Color.FromArgb(176, 190, 197);
    }

    private void BtnStart_Click(object? sender, EventArgs e)
    {
        AcceptedAt = DateTime.Now;
    }
}
